//! Golden datagrams for the C and Python clients' tests. The files in
//! `clients/` are generated from these by
//! `cargo run -p virtual-sync --example vectors`, and a test fails if the
//! committed files drift from the encoder.

use crate::mac::derive_key;
use crate::protocol::{ControlValue, Message, NodeKind, control_id, encode, streams};

pub const PASSPHRASE: &str = "dance floor";

/// (name, datagram) pairs: every message kind, signed, plus one unsigned.
pub fn vectors() -> Vec<(&'static str, Vec<u8>)> {
    let key = derive_key(PASSPHRASE);
    let messages = [
        (
            "announce",
            Message::Announce {
                name: "Main room".into(),
                streams: streams::ALL,
                zones: 4,
                port: 50_000,
            },
        ),
        (
            "hello",
            Message::Hello {
                name: "Strip".into(),
                kind: NodeKind::Light,
                streams: streams::CLOCK | streams::ZONES,
            },
        ),
        (
            "clock",
            Message::Clock {
                leader_us: 5_000_000,
                beat: 33.5,
                bpm: 128.0,
                beats_per_bar: 4,
                playing: true,
            },
        ),
        (
            "controls",
            Message::Controls {
                snapshot: false,
                values: vec![
                    ControlValue {
                        id: control_id("deck.0.level"),
                        value: 0.75,
                    },
                    ControlValue {
                        id: control_id("master.blackout"),
                        value: 1.0,
                    },
                ],
            },
        ),
        (
            "audio",
            Message::Audio {
                level: 0.5,
                bass: 0.875,
                mid: 0.25,
                high: 0.125,
                hit: 1.0,
                bands: [0.0, 0.125, 0.25, 0.375, 0.5, 0.625, 0.75, 0.875],
            },
        ),
        (
            "zones",
            Message::Zones {
                colors: vec![[255, 0, 0], [0, 255, 0], [0, 0, 255], [10, 20, 30]],
            },
        ),
        ("ping", Message::Ping { follower_us: 1234 }),
        (
            "pong",
            Message::Pong {
                follower_us: 1234,
                leader_us: 99_999,
            },
        ),
    ];
    let mut out: Vec<_> = messages
        .iter()
        .enumerate()
        .map(|(index, (name, message))| {
            (
                *name,
                encode(message, 0x1234_5678, 100 + index as u32, key).expect("fits"),
            )
        })
        .collect();
    out.push((
        "clock_unsigned",
        encode(&messages[2].1, 0x1234_5678, 200, None).expect("fits"),
    ));
    out
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// `clients/c/test/vectors.h`.
pub fn c_header() -> String {
    let mut out = String::from(
        "/* Generated by `cargo run -p virtual-sync --example vectors`. Do not edit. */\n\
         #include <stdint.h>\n#include <stddef.h>\n",
    );
    out.push_str(&format!(
        "static const char *VS_TEST_PASSPHRASE = \"{PASSPHRASE}\";\n"
    ));
    for (name, bytes) in vectors() {
        let body: Vec<String> = bytes.iter().map(|b| format!("0x{b:02x}")).collect();
        out.push_str(&format!(
            "static const uint8_t VS_VECTOR_{}[{}] = {{{}}};\n",
            name.to_uppercase(),
            bytes.len(),
            body.join(",")
        ));
    }
    out
}

/// `clients/test-vectors.json`.
pub fn json() -> String {
    let entries: Vec<String> = vectors()
        .iter()
        .map(|(name, bytes)| format!("    {{\"name\": \"{name}\", \"hex\": \"{}\"}}", hex(bytes)))
        .collect();
    format!(
        "{{\n  \"passphrase\": \"{PASSPHRASE}\",\n  \"vectors\": [\n{}\n  ]\n}}\n",
        entries.join(",\n")
    )
}
